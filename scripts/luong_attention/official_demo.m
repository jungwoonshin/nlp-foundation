function official_demo(workDir)
% Run the unmodified, pinned official implementation on shared prepared data.
% First: python scripts/luong_attention/demo.py --work-dir WORK_DIR --prepare-only
% MATLAB: addpath('scripts/luong_attention'); official_demo('ABSOLUTE_WORK_DIR')
  assert(isfolder(workDir), 'Experiment directory is missing.');
  originalDir = pwd;
  restoreDir = onCleanup(@() cd(originalDir));
  cd(workDir);
  workDir = pwd;
  codeDir = fullfile(workDir, 'official', 'code');
  addpath(genpath(codeDir));
  assert(gpuDeviceCount > 0, 'A MATLAB-supported GPU is required.');
  gpu = gpuDevice(1);
  cd(codeDir);
  dataDir = fullfile(workDir, 'prepared');
  manifest = jsondecode(fileread(fullfile(workDir, 'dataset-manifest.json')));
  assert(strcmp(manifest.official_commit, '32f8564e39d4a3d30fa57038e44f4a3dbdc2068c'));
  kinds = {'local_m', 'local_p'};
  functions = [2, 4];
  for ii = 1:numel(kinds)
    outDir = fullfile(workDir, 'runs', ['official_' kinds{ii}]);
    assert(~isfolder(outDir), 'Output already exists; choose a fresh work directory.');
    mkdir(outDir);
    start = tic;
    trainLSTM(fullfile(dataDir, 'train.10k'), fullfile(dataDir, 'valid.100'), ...
      fullfile(dataDir, 'test.100'), 'de', 'en', ...
      fullfile(dataDir, 'train.10k.de.vocab.1000'), ...
      fullfile(dataDir, 'train.10k.en.vocab.1000'), outDir, ...
      'attnFunc', functions(ii), 'attnOpt', 2, 'posWin', 10, ...
      'numLayers', 1, 'lstmSize', 100, 'dropout', 1, ...
      'batchSize', 128, 'numEpoches', 10, 'learningRate', 1, ...
      'finetuneEpoch', 5, 'finetuneRate', 0.5, 'epochFraction', 1, ...
      'epochIter', 79, 'maxSentLen', 51, 'maxGradNorm', 5, ...
      'initRange', 0.1, 'seed', 42, 'sortBatch', 1, 'shuffle', 1, ...
      'isReverse', 1, 'feedInput', 1, 'normLocalAttn', 0, ...
      'gpuDevice', 1, 'dataType', 'single', 'isResume', 0, 'decode', 0);
    wait(gpu);
    elapsed = toc(start);
    saved = load(fullfile(outDir, 'modelRecent.mat'), 'params');
    assert(saved.params.isGPU == 1, 'Official trainer did not use GPU.');
    assert(saved.params.iter == 790, 'Expected the final 10-epoch checkpoint.');
    result = struct('implementation', 'official MATLAB', 'kind', kinds{ii}, ...
      'score', 'general', 'test_perplexity', saved.params.curTestPerpWord, ...
      'test_mean_nll', log(saved.params.curTestPerpWord), ...
      'training_seconds', elapsed, 'gpu', gpu.Name, 'matlab', version, ...
      'official_commit', manifest.official_commit, 'seed', 42, ...
      'checkpoint_policy', 'final epoch 10');
    fid = fopen(fullfile(outDir, 'results.json'), 'w');
    fprintf(fid, '%s\n', jsonencode(result));
    fclose(fid);
  end
end
